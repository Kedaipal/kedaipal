// Generates the buyer phone picker's country table from Google's libphonenumber
// metadata (via the `libphonenumber-js` devDependency — it never ships in a
// bundle; only this script reads it).
//
// Usage: node scripts/generate-dial-codes.mjs
//
// Writes two checked-in modules (never hand-edit them — re-run this instead):
//   convex/lib/dialCodes.ts         dial code, trunk prefix, mobile NSN lengths
//                                   and the main country of a shared code, per
//                                   ISO country. Imported by the validator and
//                                   the display helpers, so it stays small: no
//                                   names.
//   convex/lib/dialCountryNames.ts  English display names, frozen here rather
//                                   than read from `Intl.DisplayNames` at
//                                   runtime so the Worker and every browser
//                                   render the same label (CLDR differs across
//                                   runtimes — "Turkey" vs "Türkiye"). Only the
//                                   picker imports it.
//
// Re-run after bumping `libphonenumber-js` (a numbering plan changed) and
// review the diff — the tests in convex/lib/dialCodes.test.ts pin the rows the
// product leans on (MY, SG, the trunk-prefix edge cases).
//
// See docs/phone-numbers.md.

import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
	getCountries,
	getCountryCallingCode,
	Metadata,
} from "libphonenumber-js/max";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const { version } = require("libphonenumber-js/package.json");
const maxMetadata = require("libphonenumber-js/metadata.max.json");

/**
 * Countries whose users the WhatsApp Business Platform cannot message at all
 * (Meta's WhatsApp Business Messaging Policy — sanctioned jurisdictions). A
 * buyer there could never receive the order confirmation, so the picker must
 * not offer them. The sanctioned regions of Ukraine share +380 with the rest of
 * the country, so they can't be excluded by dial code; Meta's per-send error
 * (130497) covers those.
 */
const WHATSAPP_UNREACHABLE = new Set(["CU", "IR", "KP", "SY"]);

const names = new Intl.DisplayNames(["en"], { type: "region" });
const callingCodes = maxMetadata.country_calling_codes;

const rows = getCountries()
	.filter((iso) => !WHATSAPP_UNREACHABLE.has(iso))
	.map((iso) => {
		const meta = new Metadata();
		meta.selectNumberingPlan(iso);
		const plan = meta.numberingPlan;
		const dial = getCountryCallingCode(iso);
		// Mobile lengths when the plan lists them (a WhatsApp number is a
		// mobile), else the country's general lengths — libphonenumber stores a
		// type with no lengths of its own that way.
		const mobile = plan.type("MOBILE")?.possibleLengths();
		const lengths = mobile?.length ? mobile : plan.possibleLengths();
		return {
			iso,
			dial,
			trunk: plan.nationalPrefix() || null,
			lengths,
			main: (callingCodes[dial] ?? [])[0] === iso,
			name: names.of(iso),
		};
	})
	.sort((a, b) => a.name.localeCompare(b.name, "en"));

const banner = (what) =>
	`// @generated by scripts/generate-dial-codes.mjs from libphonenumber-js ${version} — do not edit by hand.\n// ${what}\n// See docs/phone-numbers.md.\n`;

const dialCodes = `${banner("Per-country dialing facts for the buyer phone picker and validator.")}
/**
 * One row per country a buyer's WhatsApp number can come from (every
 * libphonenumber region except the four WhatsApp Business cannot message).
 *
 * - \`dial\`    — the ITU calling code. Codes are prefix-free, so a stored
 *               number's code is its first 1–3 digits that match a row.
 * - \`trunk\`   — the national (trunk) prefix a local dials before the number
 *               (\`0\` in most places, \`8\` in Russia, \`1\` across +1, \`06\` in
 *               Hungary), or null where the leading digit is PART of the number
 *               (Italy, Côte d'Ivoire, Singapore) and must never be stripped.
 * - \`lengths\` — the national significant number lengths of a MOBILE there.
 * - \`main\`    — the country a shared code resolves to (US for +1, GB for +44)
 *               when nothing else says which.
 */
export const DIAL_ROWS = [
${rows
	.map(
		(r) =>
			`\t{ iso: ${JSON.stringify(r.iso)}, dial: ${JSON.stringify(r.dial)}, trunk: ${JSON.stringify(r.trunk)}, lengths: [${r.lengths.join(", ")}], main: ${r.main} },`,
	)
	.join("\n")}
] as const;

export type DialIso = (typeof DIAL_ROWS)[number]["iso"];
`;

const dialNames = `${banner("English country names for the buyer phone picker's options.")}
import type { DialIso } from "./dialCodes";

export const DIAL_COUNTRY_NAMES: Record<DialIso, string> = {
${rows.map((r) => `\t${r.iso}: ${JSON.stringify(r.name)},`).join("\n")}
};
`;

await writeFile(path.join(root, "convex/lib/dialCodes.ts"), dialCodes);
await writeFile(path.join(root, "convex/lib/dialCountryNames.ts"), dialNames);
console.log(
	`libphonenumber-js ${version}: wrote ${rows.length} countries (excluded ${[...WHATSAPP_UNREACHABLE].join(", ")})`,
);
